// ---------------------------------------------------------------------------
// ۴. موتور جستجوی پاسخ‌های ایمن (Verified Fast-Path Search)
// ---------------------------------------------------------------------------

export function findVerifiedSafeResponse(userInput: string): VerifiedSafeItem | null {
  if (!userInput) return null;
  const cleanInput = userInput.trim().toLowerCase();

  // ۱. بررسی تطابق با الگوهای Regex
  for (const item of SAFE_VERIFIED_RESPONSES) {
    for (const pattern of item.patterns) {
      if (pattern.test(cleanInput)) {
        return item;
      }
    }
  }

  // ۲. بررسی تطابق با کلیدواژه‌های اصلی
  for (const item of SAFE_VERIFIED_RESPONSES) {
    const matched = item.keywords.some((kw) => cleanInput.includes(kw.toLowerCase()));
    if (matched) {
      return item;
    }
  }

  return null;
}

// ---------------------------------------------------------------------------
// ۵. لایه اعتبارسنجی محاسبات ریاضی (Validation & Self-Correction Layer)
// ---------------------------------------------------------------------------

/**
 * این تابع تمام عبارات حسابی (جمع، تفریق، ضرب، تقسیم) موجود در متن را استخراج،
 * درستی ریاضی آن‌ها را با دقت بالا محاسبه و تایید می‌کند و در صورت وجود اشتباه،
 * متن را اصلاح کرده و گزارش خطا تهیه می‌کند.
 */
export function validateAndCorrectTutorResponse(rawText: string): ValidationResult {
  const issues: MathValidationIssue[] = [];
  let cleanText = rawText;
  let corrected = false;

  // قانون ۱: اجبار ارقام فارسی (تبدیل ارقام انگلیسی خارج از تگ‌های SVG یا کدهای HTML به فارسی)
  // برای محافظت از تگ‌های SVG یا ویژگی‌های عددی، متن را با احتیاط بررسی می‌کنیم
  const svgRegex = /<svg[\s\S]*?<\/svg>/gi;
  const svgs: string[] = [];
  const textWithoutSvg = cleanText.replace(svgRegex, (match) => {
    svgs.push(match);
    return `___SVG_PLACEHOLDER_${svgs.length - 1}___`;
  });

  let textWithPersianDigits = textWithoutSvg;
  if (/[0-9]/.test(textWithoutSvg)) {
    issues.push({
      type: 'english_digits',
      expression: 'ارقام انگلیسی در پاسخ مدل',
      correctionText: 'تبدیل خودکار به ارقام زیبای فارسی'
    });
    textWithPersianDigits = toPersianDigits(textWithoutSvg);
    corrected = true;
  }

  // قانون ۲: اعتبارسنجی معادلات ریاضی و روابط حسابی
  // الگوهای تشخیص: عدد [عملگر] عدد = عدد
  // عملگرها: + یا - یا × یا * یا ÷ یا /
  const mathEqRegex = /([۰-۹0-9]+)\s*([\+\-\×\*\÷\/])\s*([۰-۹0-9]+)\s*(=|برابر است با|مساوی با|میشه)\s*([۰-۹0-9]+)/g;

  let match;
  while ((match = mathEqRegex.exec(textWithPersianDigits)) !== null) {
    const fullMatch = match[0];
    const n1 = parseInt(toEnglishDigits(match[1]), 10);
    const op = match[2];
    const n2 = parseInt(toEnglishDigits(match[3]), 10);
    const expectedEqWord = match[4];
    const givenResult = parseInt(toEnglishDigits(match[5]), 10);

    let calculated: number | null = null;
    if (op === '+' || op === '＋') calculated = n1 + n2;
    else if (op === '-' || op === '−') calculated = n1 - n2;
    else if (op === '×' || op === '*') calculated = n1 * n2;
    else if (op === '÷' || op === '/') calculated = n2 !== 0 ? Math.floor(n1 / n2) : null;

    if (calculated !== null && calculated !== givenResult) {
      // کشف خطای محاسباتی مدل!
      const correctExpr = `${toPersianDigits(n1)} ${op} ${toPersianDigits(n2)} = ${toPersianDigits(calculated)}`;
      issues.push({
        type: 'arithmetic_error',
        expression: fullMatch,
        foundValue: givenResult,
        expectedValue: calculated,
        correctionText: correctExpr
      });

      // جایگزینی فوری با محاسبه کاملاً صحیح و استاندارد
      textWithPersianDigits = textWithPersianDigits.replace(
        fullMatch,
        `${toPersianDigits(n1)} ${op} ${toPersianDigits(n2)} ${expectedEqWord} ${toPersianDigits(calculated)}`
      );
      corrected = true;
    }
  }

  // قانون ۳: جلوگیری از لو رفتن ناگهانی پاسخ نهایی (Socratic leak)
  const leakPatterns = [
    /(?:جواب|پاسخ)\s+نهایی\s+(?:برابر\s+است\s+با|مساوی\s+است\s+با|می‌شود|میشه)\s+([۰-۹0-9]+)/gi,
    /(?:حاصل|جواب)\s+این\s+مسئله\s+([۰-۹0-9]+)\s+است/gi
  ];

  for (const pattern of leakPatterns) {
    if (pattern.test(textWithPersianDigits)) {
      issues.push({
        type: 'direct_answer_leak',
        expression: 'لو دادن مستقیم جواب نهایی در روش سقراطی',
        correctionText: 'حفظ لحن سقراطی و پرسش تعاملی از کودک'
      });
      textWithPersianDigits = textWithPersianDigits.replace(
        pattern,
        'بیا با هم حساب کنیم ببینیم به چه عددی می‌رسیم!'
      );
      corrected = true;
    }
  }

  // بازگرداندن SVGها به متن نهایی
  cleanText = textWithPersianDigits.replace(/___SVG_PLACEHOLDER_(\d+)___/g, (_, index) => {
    return svgs[parseInt(index, 10)] || '';
  });

  return {
    isValid: issues.filter(i => i.type === 'arithmetic_error').length === 0,
    cleanText,
    corrected,
    issues
  };
}
